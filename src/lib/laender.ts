/** Umlaute als ae/oe/ue, weil iShares beides schreibt. */
function schluessel(name: string): string {
  return name.trim().toLowerCase().replaceAll('ä', 'ae').replaceAll('ö', 'oe').replaceAll('ü', 'ue').replaceAll('ß', 'ss');
}

export function landKuerzel(name: string): string | undefined {
  return KUERZEL[schluessel(name)];
}
